// ---- Types used by the other language files and by t() ----
type PluralForm = "zero" | "one" | "two" | "few" | "many";

/** Every key that must exist in every language. */
export type MessageKey = Exclude<keyof typeof en, `${string}.${PluralForm}`>;

/** Base name of a plural text, e.g. "post.comments". */
export type PluralKey = Extract<MessageKey, `${string}.other`> extends infer K
  ? K extends `${infer B}.other`
    ? B
    : never
  : never;

/** What a language file must look like. */
export type Messages = Record<MessageKey, string> &
  Partial<Record<`${PluralKey}.${PluralForm}`, string>>;
